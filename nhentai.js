    async apiLogin(username, password, captchaResponse, powChallenge, powNonce) {
        const data = await this.loginRequest('/auth/login', {
            username: username.trim(),
            password,
            captcha_response: captchaResponse.replace(/\s+/g, ''),
            pow_challenge: powChallenge,
            pow_nonce: powNonce,
            pow_action: 'login',
        })
        if (!data.access_token) throw new Error('Access token missing from login response')
        return data
    }

    loginSession(id) {
        const session = this._loginSessions.get(id)
        if (!session) throw new Error('Login cancelled')
        return session
    }

    async solvePowNonce(id, challenge, difficulty, maxIterations = 3000000) {
        for (let nonce = 0; nonce < maxIterations; nonce++) {
            // Yield to Flutter and allow back/cancel while solving the challenge.
            if (nonce % 256 === 0) {
                await new Promise(resolve => setTimeout(resolve, 0))
                this.loginSession(id)
            }
            const digest = new Uint8Array(Convert.sha256(Convert.encodeUtf8(challenge + nonce)))
            let remaining = difficulty
            let valid = true
            for (const byte of digest) {
                if (remaining <= 0) break
                if (remaining >= 8) {
                    if (byte !== 0) { valid = false; break }
                    remaining -= 8
                } else {
                    valid = (byte & ((0xff << (8 - remaining)) & 0xff)) === 0
                    remaining = 0
                    break
                }
            }
            if (valid && remaining <= 0) return String(nonce)
        }
        throw new Error('PoW nonce not found within ' + maxIterations + ' iterations')
    }

    loginWebviewScript() {
        // Evaluated in the website, not in the source JS runtime. The native
        // bridge polls the return value; no platform-specific handler is needed.
        return `(() => {
            const state = window.__nhentaiScriptLogin ||
                (window.__nhentaiScriptLogin = { token: '' });
            if (typeof turnstile !== 'undefined' && !state.hooked) {
                const originalRender = turnstile.render;
                turnstile.render = function(container, params) {
                    const originalCallback = params.callback;
                    params.callback = function(token) {
                        state.token = token;
                        if (originalCallback) originalCallback(token);
                    };
                    return originalRender.call(this, container, params);
                };
                state.hooked = true;
            }
            const input = document.querySelector('input[name="cf-turnstile-response"]') ||
                document.querySelector('[name="captcha_response"]');
            return {
                url: location.href,
                title: document.title,
                userAgent: navigator.userAgent,
                token: input ? input.value : state.token
            };
        })()`
    }

