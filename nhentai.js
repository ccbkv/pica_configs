    async randomComicId() {
        const first = await this.searchApi('', 1, 'date')
        if (!first.num_pages) throw new Error('Failed to get random comic')
        const page = Date.now() % first.num_pages + 1
        const result = await this.searchApi('', page, 'date')
        if (!result.result?.length) throw new Error('Failed to get random comic')
        return String(result.result[Date.now() % result.result.length].id)
    }

    relativeTime(seconds) {
        const elapsed = Date.now() - seconds * 1000
        if (elapsed < 0) return 'Error'
        const days = Math.floor(elapsed / 86400000)
        if (days > 360) return Math.floor(days / 360) + ' 年前'
        if (days > 30) return Math.floor(days / 30) + ' 个月前'
        if (Math.floor(elapsed / 3600000) > 24) return days + ' 天前'
        if (Math.floor(elapsed / 60000) > 60) return Math.floor(elapsed / 3600000) + ' 小时前'
        if (Math.floor(elapsed / 1000) > 60) return Math.floor(elapsed / 60000) + ' 分钟前'
        return '刚刚'
    }

