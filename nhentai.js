    async tokens() {
        const cookies = await Network.getCookies(this.baseUrl)
        const get = name => (cookies || []).find(c => c.name === name)?.value || ''
        return {
            access_token: get('access_token'),
            refresh_token: get('refresh_token'),
        }
    }

    saveTokens(accessToken, refreshToken) {
        Network.setCookies(this.baseUrl, [
            { name: 'access_token', value: accessToken, domain: '.nhentai.net', path: '/' },
            { name: 'refresh_token', value: refreshToken, domain: '.nhentai.net', path: '/' },
        ])
        this.logged = true
    }

    async refreshAccessToken() {
        if (this._refreshing) return this._refreshing
        const generation = this._authGeneration
        this._refreshing = (async () => {
            try {
                const tokens = await this.tokens()
                if (!tokens.refresh_token) return false
                const result = await this.request('POST', '/auth/refresh',
                    { refresh_token: tokens.refresh_token })
                if (!result.access_token || !result.refresh_token ||
                    generation !== this._authGeneration) return false
                this.saveTokens(result.access_token, result.refresh_token)
                return true
            } catch (_) {
                return false
            }
        })()
        try {
            return await this._refreshing
        } finally {
            this._refreshing = null
        }
    }

    async request(method, path, data = null, withAuth = false, retried = false) {
        const headers = { ...this.headers }
        if (data != null) headers['Content-Type'] = 'application/json'
        if (withAuth) {
            const tokens = await this.tokens()
            if (tokens.access_token) headers.Authorization = 'User ' + tokens.access_token
        }
        const res = await Network.sendRequest(method, this.apiUrl + path,
            headers, data == null ? null : JSON.stringify(data))
        if (res.status === 401 || (method !== 'GET' && res.status === 403)) {
            if (withAuth && !retried && await this.refreshAccessToken()) {
                return this.request(method, path, data, true, true)
            }
            this.logged = false
            throw new Error('login required')
        }
        if (res.status !== 200) {
            throw new Error('nhentai HTTP ' + res.status +
                (res.status === 403 ? ': 请先完成网站验证' : ''))
        }
        if (res.body == null || res.body === '') return {}
        try {
            return typeof res.body === 'string' ? JSON.parse(res.body) : res.body
        } catch (_) {
            throw new Error('nhentai 返回了非 JSON 数据，请检查网站验证状态')
        }
    }

