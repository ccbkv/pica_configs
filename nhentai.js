    // NhentaiCategoryFilter.fromParam / buildNhentaiCategoryQueryFromParam.
    // Only /search/ values are URI-decoded. Other namespace values remain literal.
    buildCategoryQuery(param, preferredLanguage = null) {
        const terms = [], numeric = { pages: [], favorites: [], uploaded: [] }
        const seen = new Set()
        for (const token of String(param || '').split('@@@').map(s => s.trim()).filter(Boolean)) {
            const parts = token.split('/').filter(Boolean)
            if (!token.startsWith('/') || parts.length < 2) continue
            const type = parts.shift()
            const value = parts.join('/')
            if (Object.prototype.hasOwnProperty.call(numeric, type)) {
                const match = (type === 'uploaded' ?
                    /^(>=|>|=|<|<=)(\d+)([hdwmy])?$/ : /^(>=|>|=|<|<=)(\d+)$/).exec(value)
                if (!match || !Number.isSafeInteger(Number(match[2]))) {
                    throw new Error('Invalid nhentai numeric filter: ' + token)
                }
                numeric[type].push({
                    comparison: match[1], value: Number(match[2]),
                    suffix: type === 'uploaded' ? (match[3] || 'd') : '',
                })
            } else {
                const decoded = type === 'search' ? decodeURIComponent(value) : value
                const key = type + '\0' + decoded
                if (!seen.has(key)) {
                    seen.add(key)
                    terms.push({ namespace: type, value: decoded })
                }
            }
        }
        const fragments = terms.map(term => term.namespace === 'search' ? term.value :
            term.namespace === 'language' ? 'language:' + term.value :
                term.namespace + ':"' + term.value + '"')
        for (const field of ['pages', 'favorites', 'uploaded']) {
            let conditions = []
            for (const condition of numeric[field]) {
                if (conditions.some(c => c.comparison === condition.comparison &&
                    c.value === condition.value && c.suffix === condition.suffix)) continue
                if (condition.comparison === '=') {
                    conditions = [condition]
                    break
                }
                const lower = c => c.comparison === '>=' || c.comparison === '>'
                if (conditions.some(c => lower(c) === lower(condition))) continue
                conditions.push(condition)
                if (conditions.length === 2) break
            }
            fragments.push(...conditions.map(c => field + ':' + c.comparison + c.value + c.suffix))
        }
        const explicitLanguage = terms.some(t => t.namespace === 'language' ||
            (t.namespace === 'search' && /(^|\s)language:/i.test(t.value)))
        if (!explicitLanguage && preferredLanguage) fragments.push('language:' + preferredLanguage)
        return fragments.join(' ')
    }

